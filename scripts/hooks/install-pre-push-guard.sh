#!/usr/bin/env bash
# Install the raw-stdin guard without changing global config or other hooks.
set -euo pipefail

[[ "$#" -eq 0 ]] || { echo 'ERROR: no arguments are accepted' >&2; exit 2; }
root="$(git rev-parse --show-toplevel)"
if git config --get core.hooksPath >/dev/null; then
  echo 'ERROR: core.hooksPath is selected; its owner must install the guard' >&2
  exit 1
else
  [[ "$?" -eq 1 ]] || exit 1
fi
common="$(git rev-parse --path-format=absolute --git-common-dir)"
python3 - "$common/hooks" "$root/scripts/hooks/pre-push-guard.sh" <<'PY'
import os
import pathlib
import re
import shlex
import stat
import sys
import tempfile

hooks, source = map(pathlib.Path, sys.argv[1:])
wrapper = '''#!/usr/bin/env bash
# hy-home.docker native pre-push guard
set -euo pipefail
root="$(git rev-parse --show-toplevel)"
exec "$root/scripts/hooks/pre-push-guard.sh" "$@"
'''
# shortcut: recognize only this pre-commit template, review any new template before replacing it.
pre_commit = '''#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03

# start templated
INSTALL_PYTHON=__PYTHON__
ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-push)
# end templated

HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS+=(--hook-dir "$HERE" -- "$@")

if [ -x "$INSTALL_PYTHON" ]; then
    exec "$INSTALL_PYTHON" -mpre_commit "${ARGS[@]}"
elif command -v pre-commit > /dev/null; then
    exec pre-commit "${ARGS[@]}"
else
    echo '`pre-commit` not found.  Did you forget to activate your virtualenv?' 1>&2
    exit 1
fi
'''

try:
    if source.is_symlink() or not source.is_file() or not os.access(source, os.X_OK):
        raise ValueError('tracked guard must be a regular executable file')
    if hooks.is_symlink() or (hooks.exists() and not hooks.is_dir()):
        raise ValueError('hook directory must be a real directory')
    hooks.mkdir(exist_ok=True)
    hook = hooks / 'pre-push'
    if hook.is_symlink() or (hook.exists() and not hook.is_file()):
        raise ValueError('existing pre-push hook is not a regular file')
    if (hooks / 'pre-push.legacy').exists() or (hooks / 'pre-push.legacy').is_symlink():
        raise ValueError('existing legacy push hook requires owner reconciliation')
    previous = hook.read_text(encoding='utf-8') if hook.exists() else None
    if previous == wrapper:
        if not os.access(hook, os.X_OK):
            raise ValueError('installed native hook is not executable')
        print('PASS: native pre-push guard already installed')
        raise SystemExit(0)
    pattern = re.escape(pre_commit).replace('__PYTHON__', r'[^\r\n]+')
    if previous is not None and re.fullmatch(pattern, previous) is None:
        raise ValueError('unknown pre-push hook; preserve it for owner reconciliation')
    if previous is not None:
        assignment = next(line for line in previous.splitlines() if line.startswith('INSTALL_PYTHON='))
        value = assignment.removeprefix('INSTALL_PYTHON=')
        words = shlex.split(value)
        if len(words) != 1 or not pathlib.Path(words[0]).is_absolute() or value != shlex.quote(words[0]):
            raise ValueError('unknown pre-commit interpreter assignment')
        backup = hooks / 'pre-push.before-native'
        with backup.open('xb') as output:
            output.write(previous.encode('utf-8'))
        backup.chmod(stat.S_IMODE(hook.stat().st_mode))
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=hooks, prefix='.pre-push-', delete=False) as output:
            temporary = pathlib.Path(output.name)
            output.write(wrapper.encode('utf-8'))
        temporary.chmod(0o755)
        os.replace(temporary, hook)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    print('PASS: native pre-push guard installed; prior shim retained if present')
except (OSError, UnicodeError, ValueError) as error:
    print(f'ERROR: {error}', file=sys.stderr)
    raise SystemExit(1) from None
PY
